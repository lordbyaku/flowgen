import { z } from 'zod';
import * as E from '@/config/enums';
import { MAX_CHARACTERS, MAX_REF_IMAGES } from '@/config/constants';
import {
  AngleSchema,
  AspectRatioSchema,
  CameraStyleSchema,
  CharacterModeSchema,
  CreativeStyleSchema,
  HookStyleSchema,
  ObjectiveSchema,
  PacingSchema,
  PlatformSchema,
  ProductTypeSchema,
  RealismSchema,
  ReferenceImageSchema,
  ScriptLanguageSchema,
  ShortText,
  Text,
  ToneSchema,
} from './common';

const List = (max = 20) => z.array(z.string().max(400)).max(max, `Maksimal ${max} item`);

export const CharacterInputSchema = z.object({
  id: z.string().min(1),
  nickname: ShortText,
  role: ShortText,
  genderPresentation: ShortText,
  approxAge: ShortText,
  ethnicLook: ShortText,
  skinTone: ShortText.optional(),
  faceShape: ShortText.optional(),
  hair: ShortText.optional(),
  hijab: z.boolean().optional(),
  facialHair: z.boolean().optional(),
  build: ShortText.optional(),
  clothing: ShortText,
  accessories: ShortText.optional(),
  expression: ShortText.optional(),
  personality: ShortText.optional(),
  relationToProduct: ShortText.optional(),
  referenceImages: z.array(ReferenceImageSchema).max(MAX_REF_IMAGES),
  restrictions: ShortText.optional(),
  fromBibleId: z.string().optional(),
});

// Field enum W (objective, realism, style, tone) bersifat opsional di skema agar draft yang
// belum lengkap tetap valid; kewajibannya ditegakkan oleh skor kelengkapan (blockers).
export const BriefSchema = z.object({
  schemaVersion: z.literal(1),
  project: z.object({
    name: ShortText,
    brandId: z.string(),
    objective: ObjectiveSchema.optional(),
    platforms: z.array(PlatformSchema).max(7),
    aspectRatio: AspectRatioSchema,
    durationSec: z.number().int().min(5, 'Durasi minimal 5 detik').max(120, 'Durasi maksimal 120 detik'),
    sceneCountMode: z.enum(['auto', 'manual']),
    sceneCount: z.number().int().min(1).max(60).optional(),
    scriptLanguage: ScriptLanguageSchema,
    regionalNote: ShortText.optional(),
  }),
  product: z.object({
    name: ShortText,
    type: ProductTypeSchema,
    category: ShortText,
    description: Text,
    benefits: List(5),
    usps: List(3),
    priceAndPromo: ShortText.optional(),
    proof: Text.optional(),
    allowedClaims: List(),
    forbiddenClaims: List(),
    usageSteps: List(),
    shapeSize: ShortText.optional(),
    dominantColors: List(6),
    materialTexture: ShortText.optional(),
    packaging: ShortText.optional(),
    logoPlacement: ShortText.optional(),
    textOnProduct: ShortText.optional(),
    softwareScreens: List().optional(),
    referenceImages: z.array(ReferenceImageSchema).max(MAX_REF_IMAGES, `Maksimal ${MAX_REF_IMAGES} gambar`),
    mustBeVisible: z.boolean(),
    minVisibleSecPerScene: z.number().min(0).max(8).optional(),
    wantCloseUp: z.boolean(),
  }),
  audience: z.object({
    ageRange: ShortText,
    gender: z.enum(E.GENDERS),
    location: ShortText.optional(),
    segment: ShortText,
    painPoint: Text,
    desire: Text.optional(),
    objection: Text.optional(),
    awareness: z.enum(E.AWARENESS).optional(),
    speechStyle: z.enum(E.SPEECH_STYLES).optional(),
    keyMessage: ShortText,
    cta: ShortText,
    offerDeadline: ShortText.optional(),
    competitorDiff: Text.optional(),
  }),
  strategy: z.object({
    angles: z.array(AngleSchema).max(2, 'Maksimal 2 angle'),
    aiPicksAngle: z.boolean(),
    hookStyles: z.array(HookStyleSchema).max(6),
    conceptAlternatives: z.union([z.literal(1), z.literal(2), z.literal(3)]),
    referenceAds: z.array(z.object({ url: z.string().max(500), liked: ShortText })).max(5),
    mustInclude: List(),
    mustAvoid: List(),
  }),
  visual: z.object({
    realism: RealismSchema.optional(),
    style: CreativeStyleSchema.optional(),
    tone: ToneSchema.optional(),
    pacing: PacingSchema.optional(),
    palette: z.array(z.string().max(30)).max(4, 'Maksimal 4 warna'),
    grading: z.enum(E.GRADINGS).optional(),
    cameraStyles: z.array(CameraStyleSchema).max(6),
    lens: z.enum(E.LENSES).optional(),
    depthOfField: z.enum(E.DOFS).optional(),
    lighting: z.array(z.enum(E.LIGHTINGS)).max(5),
    dominantShots: z.array(z.enum(E.SHOTS)).max(5),
    transitions: z.array(z.enum(E.TRANSITIONS)).max(5),
    referenceVideoUrl: z.string().max(500).optional(),
  }),
  characters: z.object({
    mode: CharacterModeSchema,
    list: z.array(CharacterInputSchema).max(MAX_CHARACTERS, `Maksimal ${MAX_CHARACTERS} karakter`),
  }),
  location: z.object({
    main: ShortText,
    indoorOutdoor: z.enum(E.INDOOR_OUTDOOR).optional(),
    timeOfDay: z.enum(E.TIMES_OF_DAY).optional(),
    weather: ShortText.optional(),
    condition: ShortText.optional(),
    extras: z.enum(E.EXTRAS).optional(),
    requiredProps: List(),
    perSceneNotes: Text.optional(),
    localFlavor: Text.optional(),
  }),
  audio: z.object({
    voiceOver: z.boolean(),
    voStyle: z.enum(E.VO_STYLES).optional(),
    characterDialogue: z.boolean(),
    musicMood: ShortText.optional(),
    sfx: ShortText.optional(),
    ambient: ShortText.optional(),
    textOverlay: z.boolean(),
    textStyle: ShortText.optional(),
    textLanguage: z.enum(E.TEXT_LANGUAGES).optional(),
    onScreenCta: ShortText.optional(),
    outroLogo: z.boolean(),
    outroSec: z.number().int().min(1).max(8).optional(),
  }),
  output: z.object({
    globalNegatives: List(30),
    variants: z.array(z.enum(E.VARIANTS)).min(1, 'Pilih minimal satu varian').max(3),
    promptLength: z.enum(E.PROMPT_LENGTHS),
    flowMode: z.enum(E.FLOW_MODES),
    /** Cara karakter/tempat disebut di prompt scene (v1.3). Kosong = 'description' (perilaku lama). */
    characterRef: z.enum(E.CHARACTER_REFS).optional(),
    extraNotes: Text.optional(),
    /** Kirim gambar referensi lokal ke AI (multimodal). Default: ya. */
    sendReferenceImages: z.boolean().optional(),
  }),
});
